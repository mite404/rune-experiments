#!/usr/bin/env python3
"""Build rune-tutorial.html from page.html.

- {{snip:NAME}}  the code between `// @snip:NAME` and its `// @end` in src/ or examples/,
                 so every snippet on the page is code that `cargo build` compiled.
- {{video:FILE}} / {{img:FILE}}  a file from media/, inlined as base64 so the page is one file.
Also writes examples/ex5_tests.rs: the Lesson 4 app plus the Exercise 5 test stub, so the stub
compiles too (`cargo test --examples --no-run`).
"""

# ── 1. IMPORTS ──────────────────────────────────────────────
import base64
import html
import pathlib
import re

# ── 2. DATA ─────────────────────────────────────────────────
ROOT = pathlib.Path(__file__).parent
SOURCES = sorted([*ROOT.glob("src/**/*.rs"), *ROOT.glob("examples/**/*.rs")])
KEYWORDS = (
    "as break const continue crate else enum false fn for if impl in let loop match mod move mut "
    "pub return self Self struct super true type use where while Some None Option Vec"
).split()
TOKEN = re.compile(
    r"(?P<com>//[^\n]*)|(?P<str>\"(?:\\.|[^\"\\])*\")|(?P<num>\b\d[\d_]*(?:\.\d+)?\b)"
    r"|(?P<kw>\b(?:" + "|".join(KEYWORDS) + r")\b)|(?P<mac>\b[a-z_]+!)|(?P<ty>\b[A-Z][A-Za-z0-9_]*\b)"
)


# ── 3. CALCULATION ──────────────────────────────────────────
def snips(text: str) -> dict[str, str]:  # → {name: code}, nested snips allowed
    out, stack = {}, []
    for line in text.splitlines():
        m = re.match(r"\s*// @snip:(\S+)", line)
        if m:
            stack.append((m.group(1), []))
            continue
        if re.match(r"\s*// @end\b", line):
            name, body = stack.pop()
            out[name] = "\n".join(body).strip("\n")
            continue
        for _, body in stack:
            body.append(line)
    assert not stack, f"unclosed snip {stack[-1][0]}"
    return out


def dedent(code: str) -> str:  # → code with its common indent removed
    lines = code.splitlines()
    pad = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
    return "\n".join(l[pad:] for l in lines)


def highlight(code: str) -> str:  # → escaped HTML with <span class=...> tokens
    out, last = [], 0
    for m in TOKEN.finditer(code):
        out.append(html.escape(code[last:m.start()]))
        out.append(f'<span class="{m.lastgroup}">{html.escape(m.group())}</span>')
        last = m.end()
    out.append(html.escape(code[last:]))
    return "".join(out)


def b64(path: pathlib.Path) -> str:  # → base64 text
    return base64.b64encode(path.read_bytes()).decode()


# ── 4. ACTIONS ──────────────────────────────────────────────
def write_ex5(all_snips: dict[str, str]) -> None:
    head = "//! Exercise 5 (generated by build.py): the Lesson 4 app plus a test stub.\n"
    head += "//! `cargo test --example ex5_tests` runs your tests.\n\n"
    body = head + all_snips["l4"] + "\n\n" + all_snips["ex5"] + "\n"
    (ROOT / "examples/ex5_tests.rs").write_text(body)


# ── 5. ORCHESTRATION ────────────────────────────────────────
def main() -> None:
    all_snips: dict[str, str] = {}
    for f in SOURCES:
        if f.name != "ex5_tests.rs" or "stubs" in f.parts:
            all_snips |= snips(f.read_text())
    write_ex5(all_snips)

    def fill(m: re.Match) -> str:
        kind, arg = m.group(1), m.group(2)
        if kind == "snip":
            return f'<pre class="code"><code>{highlight(dedent(all_snips[arg]))}</code></pre>'
        data = b64(ROOT / "media" / arg)
        if kind == "video":
            return (f'<video autoplay loop muted playsinline controls '
                    f'src="data:video/mp4;base64,{data}"></video>')
        return f'<img alt="" src="data:image/png;base64,{data}">'

    page = re.sub(r"\{\{(snip|video|img):([^}]+)\}\}", fill, (ROOT / "page.html").read_text())
    assert "{{" not in page, "unfilled placeholder"
    (ROOT / "rune-tutorial.html").write_text(page)
    print(f"wrote rune-tutorial.html ({len(page) // 1024} KB, {len(all_snips)} snippets)")


if __name__ == "__main__":
    main()
